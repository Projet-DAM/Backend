@Composable
fun ParentScreen(navController: NavController, vm: ParentHomeViewModel, onLogout: () -> Unit = { Log.w("ParentScreen", "DEFAULT LOGOUT CALLED - NO REAL CALLBACK PROVIDED!") }) {
    Log.d("ParentScreen", "ParentScreen created. Testing onLogout callback immediately...")
    // Test the callback to make sure it's working
    LaunchedEffect(Unit) {
        Log.d("ParentScreen", "Callback test - this should trigger MainActivity logout if working properly")
        // Don't actually call onLogout here, just log that we could
    }
    val uiState by vm.uiState.collectAsState()
    val snackbarHostState = remember { SnackbarHostState() }
    val context = LocalContext.current

    // Shared ViewModel for Suivis
    val activity = LocalContext.current as ComponentActivity
    val application = LocalContext.current.applicationContext as android.app.Application
    val sharedVm: SuiviSharedViewModel = composeViewModel(
        viewModelStoreOwner = activity,
        factory = SuiviSharedViewModelFactory(application)
    )
    val suivisMap by sharedVm.suivisByChild.collectAsState()

    // Local State
    var searchQuery by remember { mutableStateOf("") }
    var showCreateDialog by remember { mutableStateOf(false) }
    var showGenerated by remember { mutableStateOf<Pair<String, String>?>(null) }
    var selectedChildId by remember { mutableStateOf("") }

    // Get parent info
    var parentName by remember { mutableStateOf("") }
    var parentPhoto by remember { mutableStateOf<String?>(null) }

    LaunchedEffect(Unit) {
        kotlinx.coroutines.delay(500)
        vm.loadData()

        // Get parent info
        try {
            val authRepo = AuthRepository(context)
            val userId = authRepo.getUserId()
            if (!userId.isNullOrBlank()) {
                val user = authRepo.getUser(userId)
                parentName = listOfNotNull(user.prenom, user.nom).joinToString(" ").ifBlank { user.email ?: "Parent" }
                parentPhoto = user.photoProfil
            }
        } catch (e: Exception) {
            parentName = "Parent"
        }
    }

    // Load and refresh suivis
    LaunchedEffect(Unit) {
        sharedVm.loadAllSuivis()
    }

    // Also refresh when child selection changes to be sure
    LaunchedEffect(selectedChildId) {
        if (selectedChildId.isNotEmpty()) {
            sharedVm.refreshForChild(selectedChildId)
        } else {
            sharedVm.loadAllSuivis()
        }
    }

    // Get all suivis and filter
    val allSuivis = remember(suivisMap, selectedChildId) {
        // Flatten all lists and remove duplicates based on suivi ID
        val allList = suivisMap.values.flatten().distinctBy { it.id }

        if (selectedChildId.isBlank()) {
            allList
        } else {
            // Filter by selected child ID
            allList.filter {
                val childId = it.enfant?.id ?: it.enfantId
                childId == selectedChildId
            }
        }
    }.sortedByDescending { it.dateSuivi }

    val filteredSuivis = remember(allSuivis, searchQuery) {
        if (searchQuery.isBlank()) {
            allSuivis
        } else {
            allSuivis.filter { suivi ->
                val childName = suivi.enfant?.let { "${it.prenom} ${it.nom}" } ?: suivi.enfantName ?: ""
                childName.contains(searchQuery, ignoreCase = true)
            }
        }
    }

    Scaffold(
        snackbarHost = { SnackbarHost(snackbarHostState) },
        containerColor = Color.Transparent,
        modifier = Modifier.fillMaxSize(),
        floatingActionButton = {
            FloatingActionButton(
                onClick = { navController.navigate("chat_list") },
                containerColor = HeaderBlue,
                contentColor = Color.White,
                shape = CircleShape
            ) {
                Icon(
                    imageVector = Icons.Default.ChatBubble,
                    contentDescription = "Chat",
                    modifier = Modifier.size(24.dp)
                )
            }
        }
    ) { innerPadding ->
        Column(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding)
        ) {
            // Simple Top Bar removed to avoid duplication with MainScreen header

            // Action Section
            // Action Section
            ParentActionSection(
                searchQuery = searchQuery,
                onSearchChange = { searchQuery = it },
                children = uiState.children,
                selectedChildId = selectedChildId,
                onChildSelect = { selectedChildId = it },
                onRefresh = {
                    sharedVm.loadAllSuivis()
                    vm.loadData()
                },
                onAiSummaryClick = {
                    if (selectedChildId.isNotEmpty()) {
                        navController.navigate("ai_summary/$selectedChildId")
                    }
                }
            )

            // Suivis List
            if (filteredSuivis.isEmpty()) {
                Box(
                    modifier = Modifier.fillMaxSize(),
                    contentAlignment = Alignment.Center
                ) {
                    Text(
                        "Aucun suivi disponible",
                        color = Color.Gray,
                        fontSize = 16.sp
                    )
                }
            } else {
                LazyColumn(
                    modifier = Modifier
                        .fillMaxSize()
                        .padding(horizontal = 16.dp),
                    verticalArrangement = Arrangement.spacedBy(16.dp),
                    contentPadding = PaddingValues(top = 16.dp, bottom = 80.dp)
                ) {
                    items(filteredSuivis) { suivi ->
                        // Find the child from the children list to get their photo
                        val childId = suivi.enfant?.id ?: suivi.enfantId
                        val child = uiState.children.find { it.id == childId }

                        SuiviCard(
                            suivi = suivi,
                            childPhoto = child?.photoProfil,
                            onDetailsClick = {
                                childId?.let { navController.navigate("$PRESENCE_DETAIL_ROUTE/$it") }
                            },
                            onAiSummaryClick = {
                                childId?.let { navController.navigate("ai_summary/$it") }
                            }
                        )
                    }
                }
            }
        }
    }

    // Dialogs
    if (showCreateDialog) {
        CreateChildDialog(
            onDismiss = { showCreateDialog = false },
            onCreated = { credentials ->
                showCreateDialog = false
                if (credentials != null) {
                    showGenerated = credentials
                    vm.loadData()
                } else {
                    vm.loadData()
                }
            },
            snackbarHostState = snackbarHostState,
            vm = vm
        )
    }

    showGenerated?.let { credentials ->
        val clipboardManager = LocalClipboardManager.current
        AlertDialog(
            onDismissRequest = { showGenerated = null },
            title = { Text("Identifiants générés", color = TextBlue) },
            text = {
                Column {
                    Text("Email: ${credentials.first}")
                    Spacer(Modifier.height(8.dp))
                    Text("Mot de passe: ${credentials.second}")
                }
            },
            confirmButton = {
                Button(onClick = {
                    clipboardManager.setText(AnnotatedString("Email: ${credentials.first}\nMot de passe: ${credentials.second}"))
                }) {
                    Text("Copier")
                }
            },
            dismissButton = {
                TextButton(onClick = { showGenerated = null }) { Text("Fermer") }
            }
        )
    }
}

