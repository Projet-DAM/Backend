@Composable
fun ParentActionSection(
    searchQuery: String,
    onSearchChange: (String) -> Unit,
    children: List<com.example.dam_front.models.User>,
    selectedChildId: String,
    onChildSelect: (String) -> Unit,
    onRefresh: () -> Unit = {},
    onAiSummaryClick: () -> Unit = {}
) {
    var showFilterDialog by remember { mutableStateOf(false) }

    // Filter Dialog
    if (showFilterDialog) {
        ChildFilterDialog(
            children = children,
            selectedChildId = selectedChildId,
            onChildSelect = {
                onChildSelect(it)
                showFilterDialog = false
            },
            onDismiss = { showFilterDialog = false }
        )
    }

    Column(
        modifier = Modifier
            .fillMaxWidth()
            .background(CardWhite)
            .padding(16.dp)
    ) {
        // Row combining Search, Refresh and Filter
        Row(
            modifier = Modifier.fillMaxWidth(),
            verticalAlignment = Alignment.CenterVertically,
            horizontalArrangement = Arrangement.spacedBy(8.dp)
        ) {
            // Search Bar
            Surface(
                modifier = Modifier.weight(1f),
                shape = RoundedCornerShape(12.dp),
                color = Color(0xFFF5F5F5),
                shadowElevation = 0.dp
            ) {
                TextField(
                    value = searchQuery,
                    onValueChange = onSearchChange,
                    placeholder = { Text("Rechercher...", color = Color.Gray.copy(alpha = 0.6f)) },
                    leadingIcon = {
                        Icon(
                            Icons.Default.Search,
                            contentDescription = null,
                            tint = Color.Gray
                        )
                    },
                    colors = TextFieldDefaults.colors(
                        focusedContainerColor = Color.Transparent,
                        unfocusedContainerColor = Color.Transparent,
                        focusedIndicatorColor = Color.Transparent,
                        unfocusedIndicatorColor = Color.Transparent
                    ),
                    modifier = Modifier.fillMaxWidth(),
                    singleLine = true
                )
            }

            // Refresh Button
            IconButton(
                onClick = onRefresh,
                modifier = Modifier.size(40.dp)
            ) {
                Icon(
                    Icons.Default.Refresh,
                    contentDescription = "Rafraîchir",
                    tint = SportyKidsBlue,
                    modifier = Modifier.size(24.dp)
                )
            }

            // Filter Icon
            IconButton(
                onClick = { showFilterDialog = true },
                modifier = Modifier
                    .size(40.dp)
                    .background(
                        color = if (selectedChildId.isNotEmpty()) SportyKidsGreen.copy(alpha = 0.2f) else Color.Transparent,
                        shape = RoundedCornerShape(12.dp)
                    )
            ) {
                Icon(
                    Icons.Default.FilterList,
                    contentDescription = "Filtrer",
                    tint = if (selectedChildId.isNotEmpty()) SportyKidsGreen else SportyKidsBlue,
                    modifier = Modifier.size(24.dp)
                )
            }

            // AI Summary Icon
            if (selectedChildId.isNotEmpty()) {
                IconButton(
                    onClick = onAiSummaryClick,
                    modifier = Modifier
                        .size(40.dp)
                        .background(
                            color = SportyKidsGreen.copy(alpha = 0.1f),
                            shape = RoundedCornerShape(12.dp)
                        )
                ) {
                    Icon(
                        Icons.Default.AutoAwesome,
                        contentDescription = "Résumé IA",
                        tint = SportyKidsGreen,
                        modifier = Modifier.size(24.dp)
                    )
                }
            }
        }
    }
}

@OptIn(ExperimentalMaterial3Api::class)
@Composable
private fun ChildFilterDialog(
    children: List<com.example.dam_front.models.User>,
    selectedChildId: String,
    onChildSelect: (String) -> Unit,
    onDismiss: () -> Unit
) {
    AlertDialog(
        onDismissRequest = onDismiss,
        title = { Text("Filtrer par enfant", color = HeaderBlue, fontWeight = FontWeight.Bold) },
        text = {
            LazyColumn(
                modifier = Modifier.heightIn(max = 300.dp),
                verticalArrangement = Arrangement.spacedBy(8.dp)
            ) {
                item {
                    FilterChip(
                        selected = selectedChildId.isEmpty(),
                        onClick = { onChildSelect("") },
                        label = { Text("Tous les enfants") },
                        colors = FilterChipDefaults.filterChipColors(
                            selectedContainerColor = IconOrange.copy(alpha = 0.2f),
                            selectedLabelColor = IconOrange
                        )
                    )
                }
                items(children) { child ->
                    FilterChip(
                        selected = selectedChildId == child.id,
                        onClick = { onChildSelect(child.id ?: "") },
                        label = { Text("${child.prenom} ${child.nom}") },
                        colors = FilterChipDefaults.filterChipColors(
                            selectedContainerColor = IconOrange.copy(alpha = 0.2f),
                            selectedLabelColor = IconOrange
                        )
                    )
                }
            }
        },
        confirmButton = {
            TextButton(onClick = onDismiss) {
                Text("Fermer", color = TextDarkGray)
            }
        },
        containerColor = Color.White,
        shape = RoundedCornerShape(16.dp)
    )
}

@Composable
fun SuiviCard(
    suivi: SuiviEnfant,
    childPhoto: String? = null,
    onDetailsClick: () -> Unit,
    onAiSummaryClick: () -> Unit = {}
) {
    val childName = suivi.enfant?.let { "${it.prenom} ${it.nom}" } ?: suivi.enfantName ?: "Élève"
    val sdf = remember { SimpleDateFormat("dd MMM yyyy", Locale.FRANCE) }
    val dateStr = suivi.dateSuivi?.let { sdf.format(it) } ?: "Date inconnue"

    val perfFloat = suivi.performance.toFloat().coerceIn(0f, 10f)
    val perfColor = when {
        perfFloat >= 8f -> SportyKidsGreen
        perfFloat >= 5f -> IconOrange
        else -> SportyKidsRed
    }

    Card(
        modifier = Modifier
            .fillMaxWidth()
            .shadow(12.dp, RoundedCornerShape(28.dp), spotColor = HeaderBlue.copy(alpha = 0.2f)),
        shape = RoundedCornerShape(28.dp),
        colors = CardDefaults.cardColors(containerColor = Color.White)
    ) {
        Column(modifier = Modifier.padding(20.dp)) {
            // Header: Profile & Status
            Row(
                verticalAlignment = Alignment.CenterVertically,
                modifier = Modifier.fillMaxWidth()
            ) {
                val photoUrl = ImageUtils.getPhotoUrl(childPhoto)
                    ?: "https://ui-avatars.com/api/?name=${childName.replace(" ", "+")}&background=4A90E2&color=fff"

                // Avatar with premium ring
                Box(
                    modifier = Modifier
                        .size(60.dp)
                        .background(
                            brush = Brush.linearGradient(colors = listOf(HeaderBlue, IconOrange, SportyKidsGreen)),
                            shape = CircleShape
                        )
                        .padding(2.dp)
                ) {
                    AsyncImage(
                        model = ImageRequest.Builder(LocalContext.current).data(photoUrl).crossfade(true).build(),
                        contentDescription = "Photo de $childName",
                        modifier = Modifier
                            .fillMaxSize()
                            .clip(CircleShape)
                            .background(Color.White, CircleShape),
                        contentScale = ContentScale.Crop
                    )
                }

                Spacer(Modifier.width(16.dp))

                Column(modifier = Modifier.weight(1f)) {
                    Text(
                        childName,
                        fontWeight = FontWeight.ExtraBold,
                        fontSize = 18.sp,
                        color = TextBlue
                    )
                    Text(
                        dateStr,
                        color = Color.Gray,
                        fontSize = 12.sp,
                        fontWeight = FontWeight.Medium
                    )
                }

                // Trophy for High Performance
                if (perfFloat >= 8f) {
                    Surface(
                        color = Color(0xFFFFF9C4),
                        shape = CircleShape,
                        modifier = Modifier.size(36.dp)
                    ) {
                        Box(contentAlignment = Alignment.Center) {
                            Icon(Icons.Default.EmojiEvents, "Trophy", tint = Color(0xFFFBC02D), modifier = Modifier.size(20.dp))
                        }
                    }
                }
            }

            Spacer(Modifier.height(20.dp))

            // Metrics visualization
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.spacedBy(12.dp)
            ) {
                // Performance Gauge
                Surface(
                    modifier = Modifier.weight(1f),
                    color = Color(0xFFF8FAFC),
                    shape = RoundedCornerShape(20.dp),
                    border = BorderStroke(1.dp, Color(0xFFF1F5F9))
                ) {
                    Column(modifier = Modifier.padding(12.dp)) {
                        Row(verticalAlignment = Alignment.CenterVertically) {
                            Icon(Icons.Default.TrendingUp, null, modifier = Modifier.size(14.dp), tint = perfColor)
                            Spacer(Modifier.width(6.dp))
                            Text("Performance", fontSize = 11.sp, fontWeight = FontWeight.Bold, color = Color.Gray)
                        }
                        Spacer(Modifier.height(8.dp))
                        Row(verticalAlignment = Alignment.Bottom) {
                            Text(perfFloat.toInt().toString(), fontSize = 24.sp, fontWeight = FontWeight.Black, color = TextBlue)
                            Text("/10", fontSize = 14.sp, fontWeight = FontWeight.Bold, color = Color.Gray, modifier = Modifier.padding(bottom = 3.dp))
                        }
                        Spacer(Modifier.height(8.dp))
                        LinearProgressIndicator(
                            progress = perfFloat / 10f,
                            modifier = Modifier.fillMaxWidth().height(6.dp).clip(CircleShape),
                            color = perfColor,
                            trackColor = perfColor.copy(alpha = 0.1f)
                        )
                    }
                }

                // Presence / Status Card
                Surface(
                    modifier = Modifier.weight(1f),
                    color = (if (suivi.presence) Color(0xFFE8F5E9) else Color(0xFFFFEBEE)).copy(alpha = 0.5f),
                    shape = RoundedCornerShape(20.dp),
                    border = BorderStroke(1.dp, (if (suivi.presence) Color(0xFFC8E6C9) else Color(0xFFFFCDD2)))
                ) {
                    Column(modifier = Modifier.padding(12.dp), horizontalAlignment = Alignment.CenterHorizontally, verticalArrangement = Arrangement.Center) {
                        Icon(
                            if (suivi.presence) Icons.Default.CheckCircle else Icons.Default.Cancel,
                            null,
                            modifier = Modifier.size(28.dp),
                            tint = if (suivi.presence) Color(0xFF2E7D32) else Color(0xFFC62828)
                        )
                        Spacer(Modifier.height(8.dp))
                        Text(
                            if (suivi.presence) "PRÉSENT" else "ABSENT",
                            fontWeight = FontWeight.Black,
                            fontSize = 12.sp,
                            color = if (suivi.presence) Color(0xFF2E7D32) else Color(0xFFC62828)
                        )
                        Text("à la séance", fontSize = 10.sp, color = Color.Gray)
                    }
                }
            }

            // Comment Insight
            if (!suivi.commentaire.isNullOrBlank()) {
                Spacer(Modifier.height(16.dp))
                Surface(
