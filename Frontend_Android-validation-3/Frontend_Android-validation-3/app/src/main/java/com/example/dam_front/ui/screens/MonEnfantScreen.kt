@Composable
private fun CreateChildDialog(
    onDismiss: () -> Unit,
    onCreated: (Pair<String, String>) -> Unit,
    snackbarHostState: SnackbarHostState,
    vm: ParentHomeViewModel
) {
    val context = LocalContext.current
    val scope = rememberCoroutineScope()
    var nom by remember { mutableStateOf("") }
    var prenom by remember { mutableStateOf("") }
    val calendar = Calendar.getInstance()
    val dateFormatter = remember { SimpleDateFormat("yyyy-MM-dd", Locale.US) }
    var dateStr by remember { mutableStateOf<String?>(null) }
    var sport by remember { mutableStateOf("") }
    var expandedSport by remember { mutableStateOf(false) }
    val availableSports = listOf(
        "football", "basketball", "tennis", "natation", "volleyball",
        "handball", "rugby", "judo", "karate", "athletisme",
        "gymnastique", "escalade", "cyclisme"
    )
    var isCreating by remember { mutableStateOf(false) }
    var photoUrl by remember { mutableStateOf<String?>(null) }
    var photoUri by remember { mutableStateOf<Uri?>(null) }
    val pickImageLauncher = rememberLauncherForActivityResult(
        contract = ActivityResultContracts.GetContent()
    ) { uri -> photoUri = uri }

    AlertDialog(
        onDismissRequest = { if (!isCreating) onDismiss() },
        title = {
            Column {
                Text("Ajouter un enfant", color = DotGreen, fontWeight = FontWeight.SemiBold)
                Spacer(Modifier.height(4.dp))
                Text(
                    "Les identifiants seront générés automatiquement.",
                    fontSize = 12.sp,
                    color = IconInactiveGray
                )
            }
        },
        text = {
            Column {
                OutlinedTextField(
                    value = nom,
                    onValueChange = { nom = it },
                    label = { Text("Nom") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth()
                )
                Spacer(Modifier.height(8.dp))
                OutlinedTextField(
                    value = prenom,
                    onValueChange = { prenom = it },
                    label = { Text("Prénom") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth()
                )
                Spacer(Modifier.height(8.dp))
                OutlinedTextField(
                    value = dateStr ?: "Sélectionner la date de naissance",
                    onValueChange = {},
                    readOnly = true,
                    trailingIcon = {
                        IconButton(onClick = {
                            DatePickerDialog(
                                context,
                                { _, y, m, d ->
                                    calendar.set(y, m, d)
                                    dateStr = dateFormatter.format(calendar.time)
                                },
                                calendar.get(Calendar.YEAR),
                                calendar.get(Calendar.MONTH),
                                calendar.get(Calendar.DAY_OF_MONTH)
                            ).show()
                        }) {
                            Icon(Icons.Default.CalendarToday, contentDescription = null, tint = SportyKidsGreen)
                        }
                    },
                    label = { Text("Date de naissance") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth()
                )
                Spacer(Modifier.height(8.dp))
                ExposedDropdownMenuBox(
                    expanded = expandedSport,
                    onExpandedChange = { expandedSport = !expandedSport }
                ) {
                    OutlinedTextField(
                        value = sport,
                        onValueChange = {},
                        readOnly = true,
                        label = { Text("Sport pratiqué *") },
                        trailingIcon = {
                            Icon(
                                imageVector = if (expandedSport) Icons.Default.ArrowDropUp else Icons.Default.ArrowDropDown,
                                contentDescription = null
                            )
                        },
                        modifier = Modifier
                            .fillMaxWidth()
                            .menuAnchor()
                    )
                    ExposedDropdownMenu(
                        expanded = expandedSport,
                        onDismissRequest = { expandedSport = false }
                    ) {
                        availableSports.forEach { sportOption ->
                            DropdownMenuItem(
                                text = { Text(sportOption.replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.getDefault()) else it.toString() }) },
                                onClick = {
                                    sport = sportOption
                                    expandedSport = false
                                }
                            )
                        }
                    }
                }
                Spacer(Modifier.height(8.dp))
                OutlinedTextField(
                    value = photoUrl ?: "",
                    onValueChange = { photoUrl = it.takeIf { s -> s.isNotBlank() } ?: null },
                    label = { Text("URL photo (optionnelle)") },
                    singleLine = true,
                    modifier = Modifier.fillMaxWidth()
                )
                Spacer(Modifier.height(8.dp))
                Row(verticalAlignment = Alignment.CenterVertically) {
                    Button(
                        onClick = { pickImageLauncher.launch("image/*") },
                        colors = ButtonDefaults.buttonColors(containerColor = Color(0xFFE8F5E8))
                    ) {
                        Text("Choisir une photo", color = SportyKidsGreen)
                    }
                    Spacer(Modifier.width(12.dp))
                    Text("ou coller une URL ci-dessous", color = IconInactiveGray, fontSize = 12.sp)
                }
            }
        },
        confirmButton = {
            val enabled = nom.isNotBlank() && prenom.isNotBlank() && !dateStr.isNullOrBlank() && sport.isNotBlank() && !isCreating
            Button(
                onClick = {
                    scope.launch {
                        isCreating = true
                        try {
                            val authRepo = AuthRepository(context)
                            var pid = authRepo.getUserId()
                            var waited = 0
                            while (pid.isNullOrBlank() && waited < 5000) {
                                kotlinx.coroutines.delay(300)
                                waited += 300
                                pid = authRepo.getUserId()
                            }
                            if (pid.isNullOrBlank()) {
                                snackbarHostState.showSnackbar("Authentification requise")
                                isCreating = false
                                return@launch
                            }
                            val dto = CreateChildRequest(
                                nom = nom.trim(),
                                prenom = prenom.trim(),
                                dateNaissance = dateStr ?: "",
                                photoProfil = photoUrl
                            )
                            vm.createChild(pid, dto) { result ->
                                scope.launch {
                                    result.onSuccess { resp ->
                                        try {
                                            photoUri?.let { uri ->
                                                try {
                                                    // Photo upload would go here if needed
                                                    // AuthRepository(context).uploadChildPhoto(resp.child.id ?: "", uri)
                                                } catch (e: Exception) {
                                                    Log.w("CreateChild", "Photo upload failed: ${e.message}")
                                                }
                                            }
                                            // Refresh parent data after successful child creation
                                            vm.loadData()
                                            onCreated(
                                                (resp.generatedCredentials?.email ?: "") to (resp.generatedCredentials?.motDePasse ?: "")
                                            )
                                        } catch (e: Exception) {
                                            Log.e("CreateChild", "Error in success handling: ${e.message}")
                                            snackbarHostState.showSnackbar("Enfant créé mais erreur lors de la finalisation")
                                        }
                                    }
                                    result.onFailure { ex ->
                                        Log.e("CreateChild", "Child creation failed: ${ex.message}")
                                        snackbarHostState.showSnackbar(ex.message ?: "Erreur lors de la création")
                                    }
                                }
                            }
                        } finally {
                            isCreating = false
                        }
                    }
                },
                enabled = enabled,
                colors = ButtonDefaults.buttonColors(containerColor = SportyKidsGreen)
            ) {
                if (isCreating) {
                    CircularProgressIndicator(
                        modifier = Modifier.size(16.dp),
                        strokeWidth = 2.dp,
                        color = Color.White
                    )
                    Spacer(Modifier.width(8.dp))
                }
                Text("Créer")
            }
        },
        dismissButton = {
            TextButton(onClick = { if (!isCreating) onDismiss() }) {
                Text("Annuler", color = AccentOrange)
            }
        }
    )
}

// Simple wrapper for MainScreen compatibility
// Wrapper with NavHost for internal navigation within the "Mon Enfant" tab
@Composable
fun MonEnfantScreen(onLogout: () -> Unit = {}) {
    val context = LocalContext.current
    val application = context.applicationContext as android.app.Application

    // Create NavController for this section
    val navController = androidx.navigation.compose.rememberNavController()

    // Create ViewModel for Parent Screen
    val vm: ParentHomeViewModel = composeViewModel(
        factory = androidx.lifecycle.ViewModelProvider.AndroidViewModelFactory.getInstance(application)
    )

    NavHost(navController = navController, startDestination = "home") {

        // Home Screen (List of children and suvies)
        composable("home") {
            ParentScreen(
                navController = navController,
                vm = vm,
                onLogout = {
                    val authRepo = AuthRepository(context)
                    kotlinx.coroutines.CoroutineScope(kotlinx.coroutines.Dispatchers.Main).launch {
                        authRepo.logout()
                        Log.d("MonEnfantScreen", "Logout requested from helper")
                        onLogout()
                    }
                }
            )
        }

        // Chat List
        composable("chat_list") {
            ContactListScreen(navController = navController)
        }

        // Chat Detail
        composable("chat/{userId}") { backStackEntry ->
            val userId = backStackEntry.arguments?.getString("userId") ?: ""
            ChatScreen(navController = navController, userId = userId)
        }

        // Suivi/Child Detail
        composable("$PRESENCE_DETAIL_ROUTE/{childId}") { backStackEntry ->
            val childId = backStackEntry.arguments?.getString("childId") ?: ""
            SuiviDetailScreen(navController = navController, childId = childId)
        }

        // AI Summary
        composable("ai_summary/{childId}") { backStackEntry ->
            val childId = backStackEntry.arguments?.getString("childId") ?: ""
            SuiviAiSummaryScreen(navController = navController, childId = childId)
        }
    }
}
